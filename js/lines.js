// Shuffle bag: every lie gets told once before any repeats.
let lieBag = [];
export function nextLie() {
  if (!lieBag.length) {
    lieBag = [...LIES];
    for (let i = lieBag.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [lieBag[i], lieBag[j]] = [lieBag[j], lieBag[i]];
    }
  }
  return lieBag.pop();
}

